import base64
from io import BytesIO
import qrcode
from django.template.loader import get_template
from xhtml2pdf import pisa


def generate_invoice_qr_data(invoice):
    """
    Format invoice information into a structured, readable string
    for QR code generation containing customer name, product count, total, etc.
    """
    # Fetch items if already prefetched or query them
    items = list(invoice.items.all())
    product_count = len(items)
    total_quantity = sum(item.quantity for item in items)

    # Format product summary lines
    products_list = []
    for item in items:
        products_list.append(f"- {item.product.name} (Qty: {item.quantity}, Price: Rs. {item.unit_price})")
    products_summary = "\n".join(products_list) if products_list else "None"

    qr_text = (
        f"=== INVOICE DETAILS ===\n"
        f"Invoice No: {invoice.invoice_number}\n"
        f"Date: {invoice.invoice_date.strftime('%d %b %Y, %I:%M %p')}\n"
        f"Customer Name: {invoice.customer.name}\n"
        f"Customer Phone: {invoice.customer.phone}\n"
        f"Product Count: {product_count} (Total Units: {total_quantity})\n"
        f"Products:\n{products_summary}\n"
        f"Subtotal: Rs. {invoice.subtotal:.2f}\n"
        f"GST Amount: Rs. {invoice.gst_amount:.2f}\n"
        f"Grand Total: Rs. {invoice.grand_total:.2f}\n"
        f"Payment Status: {invoice.payment_status}\n"
        f"Generated by: Advance Billing System"
    )
    return qr_text


def generate_invoice_qr_base64(invoice, box_size=6, border=2):
    """
    Generate a QR code image encoded as a Base64 data URI string.
    Suitable for embedding directly into HTML and PDFs via <img src="...">.
    """
    data = generate_invoice_qr_data(invoice)
    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=box_size,
        border=border,
    )
    qr.add_data(data)
    qr.make(fit=True)

    img = qr.make_image(fill_color="#0f172a", back_color="#ffffff")
    buffer = BytesIO()
    img.save(buffer, format="PNG")
    encoded = base64.b64encode(buffer.getvalue()).decode("utf-8")
    return f"data:image/png;base64,{encoded}"


def generate_invoice_qr_bytes(invoice, box_size=8, border=2):
    """
    Generate raw PNG bytes of the QR code.
    Suitable for direct HTTP image streaming / downloads.
    """
    data = generate_invoice_qr_data(invoice)
    qr = qrcode.QRCode(
        version=1,
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=box_size,
        border=border,
    )
    qr.add_data(data)
    qr.make(fit=True)

    img = qr.make_image(fill_color="#0f172a", back_color="#ffffff")
    buffer = BytesIO()
    img.save(buffer, format="PNG")
    return buffer.getvalue()


def render_to_pdf(template_src, context_dict=None):
    """
    Render an HTML template to a PDF binary stream using xhtml2pdf.
    Returns HttpResponse or None on failure.
    """
    if context_dict is None:
        context_dict = {}
    template = get_template(template_src)
    html = template.render(context_dict)
    result = BytesIO()
    pdf = pisa.pisaDocument(BytesIO(html.encode("UTF-8")), result)
    if not pdf.err:
        return result.getvalue()
    return None
